-- =============================================================================
-- 15. VALIDATE WAYBILL -> ORDER
-- =============================================================================
-- Waybill can only be created for a confirmed order.
-- Also validates company_id consistency.
-- =============================================================================

CREATE OR REPLACE FUNCTION public.validate_waybill_company_and_order()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_order_company uuid;
  v_order_status public.order_status;
BEGIN

  SELECT
    o.company_id,
    o.status
  INTO
    v_order_company,
    v_order_status
  FROM public.orders o
  WHERE o.id = NEW.order_id;

  IF v_order_company IS NULL THEN
    RAISE EXCEPTION
      'Order % does not exist',
      NEW.order_id;
  END IF;


  IF NEW.company_id <> v_order_company THEN
    RAISE EXCEPTION
      'Waybill company_id does not match order company_id';
  END IF;


  IF v_order_status <> 'confirmed' THEN
    RAISE EXCEPTION
      'A waybill can only be created for a confirmed order';
  END IF;


  -- Automatically populate issued_at
  IF NEW.status IN (
    'issued',
    'loading_confirmed'
  )
  AND NEW.issued_at IS NULL
  THEN
    NEW.issued_at :=
      timezone('utc', now());
  END IF;


  RETURN NEW;
END;
$$;


CREATE TRIGGER trg_validate_waybill_company_and_order
  BEFORE INSERT OR UPDATE ON public.waybills
  FOR EACH ROW
  EXECUTE FUNCTION public.validate_waybill_company_and_order();


-- =============================================================================
-- 16. VALIDATE WAYBILL ITEM LINKS
-- =============================================================================
-- Ensures:
--   order_item belongs to the same order
--   product matches order item
--   quantity matches order item
--   weight matches order item
--   company_id matches
-- =============================================================================

CREATE OR REPLACE FUNCTION public.validate_waybill_item_links()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_item_company uuid;
  v_item_order_id uuid;
  v_item_product_id uuid;
  v_item_quantity integer;
  v_item_weight smallint;

  v_waybill_company uuid;
  v_waybill_order_id uuid;
  v_waybill_status public.waybill_status;

  v_product_name text;
BEGIN

  -- ---------------------------------------------------------------------------
  -- Get order item
  -- ---------------------------------------------------------------------------

  SELECT
    oi.company_id,
    oi.order_id,
    oi.product_id,
    oi.quantity,
    oi.weight_kg_snapshot
  INTO
    v_item_company,
    v_item_order_id,
    v_item_product_id,
    v_item_quantity,
    v_item_weight
  FROM public.order_items oi
  WHERE oi.id = NEW.order_item_id
    AND oi.deleted_at IS NULL;


  IF v_item_company IS NULL THEN
    RAISE EXCEPTION
      'Order item % does not exist or is deleted',
      NEW.order_item_id;
  END IF;


  -- ---------------------------------------------------------------------------
  -- Get waybill
  -- ---------------------------------------------------------------------------

  SELECT
    w.company_id,
    w.order_id,
    w.status
  INTO
    v_waybill_company,
    v_waybill_order_id,
    v_waybill_status
  FROM public.waybills w
  WHERE w.id = NEW.waybill_id
    AND w.deleted_at IS NULL;


  IF v_waybill_company IS NULL THEN
    RAISE EXCEPTION
      'Waybill % does not exist or is deleted',
      NEW.waybill_id;
  END IF;


  -- ---------------------------------------------------------------------------
  -- Company validation
  -- ---------------------------------------------------------------------------

  IF NEW.company_id <> v_waybill_company
     OR NEW.company_id <> v_item_company
  THEN
    RAISE EXCEPTION
      'Company mismatch between waybill item, waybill and order item';
  END IF;


  -- ---------------------------------------------------------------------------
  -- Order validation
  -- ---------------------------------------------------------------------------

  IF v_item_order_id <> v_waybill_order_id THEN
    RAISE EXCEPTION
      'Order item % does not belong to waybill order %',
      NEW.order_item_id,
      v_waybill_order_id;
  END IF;


  -- ---------------------------------------------------------------------------
  -- Product validation
  -- ---------------------------------------------------------------------------

  IF NEW.product_id <> v_item_product_id THEN
    RAISE EXCEPTION
      'Waybill item product does not match order item product';
  END IF;


  -- ---------------------------------------------------------------------------
  -- Quantity validation
  -- ---------------------------------------------------------------------------

  IF NEW.quantity <> v_item_quantity THEN
    RAISE EXCEPTION
      'Waybill item quantity must match the order item quantity';
  END IF;


  -- ---------------------------------------------------------------------------
  -- Weight validation
  -- ---------------------------------------------------------------------------

  IF NEW.weight_kg_snapshot <> v_item_weight THEN
    RAISE EXCEPTION
      'Waybill item weight must match the order item weight';
  END IF;


  -- ---------------------------------------------------------------------------
  -- Prevent modification after final states
  -- ---------------------------------------------------------------------------

  IF v_waybill_status IN (
    'loading_confirmed',
    'cancelled'
  )
  THEN
    RAISE EXCEPTION
      'Items cannot be added or changed after loading confirmation or cancellation';
  END IF;


  -- ---------------------------------------------------------------------------
  -- Automatically populate product snapshot if empty
  -- ---------------------------------------------------------------------------

  IF NEW.product_name_snapshot IS NULL
     OR btrim(NEW.product_name_snapshot) = ''
  THEN

    SELECT p.name
    INTO v_product_name
    FROM public.products p
    WHERE p.id = NEW.product_id;

    NEW.product_name_snapshot :=
      COALESCE(v_product_name, '');

  END IF;


  RETURN NEW;
END;
$$;


CREATE TRIGGER trg_validate_waybill_item_links
  BEFORE INSERT OR UPDATE ON public.waybill_items
  FOR EACH ROW
  EXECUTE FUNCTION public.validate_waybill_item_links();


-- =============================================================================
-- 17. WAYBILL MUST HAVE AT LEAST ONE ITEM BEFORE ISSUE
-- =============================================================================

CREATE OR REPLACE FUNCTION public.ensure_waybill_has_items()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN

  IF NEW.status IN (
    'issued',
    'loading_confirmed'
  )
  THEN

    IF NOT EXISTS (
      SELECT 1
      FROM public.waybill_items wi
      WHERE wi.waybill_id = NEW.id
        AND wi.deleted_at IS NULL
    )
    THEN

      RAISE EXCEPTION
        'Waybill % must contain at least one active item before it can be issued',
        NEW.id;

    END IF;

  END IF;


  RETURN NEW;
END;
$$;


CREATE CONSTRAINT TRIGGER trg_waybill_must_have_items
  AFTER INSERT OR UPDATE OF status ON public.waybills
  DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW
  EXECUTE FUNCTION public.ensure_waybill_has_items();


-- =============================================================================
-- 18. CREATE LOADING RECORD WHEN WAYBILL IS ISSUED
-- =============================================================================

CREATE OR REPLACE FUNCTION public.ensure_loading_for_issued_waybill()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN

  IF NEW.status = 'issued'
     AND NEW.deleted_at IS NULL
  THEN

    INSERT INTO public.loading (
      company_id,
      waybill_id,
      status,
      loading_date
    )
    VALUES (
      NEW.company_id,
      NEW.id,
      'pending',
      NEW.waybill_date
    )

    ON CONFLICT (
      company_id,
      waybill_id
    )
    WHERE deleted_at IS NULL
    DO NOTHING;

  END IF;


  RETURN NEW;
END;
$$;


CREATE TRIGGER trg_create_loading_on_waybill_issue
  AFTER INSERT OR UPDATE OF status ON public.waybills
  FOR EACH ROW
  EXECUTE FUNCTION public.ensure_loading_for_issued_waybill();


-- =============================================================================
-- 19. SYNC WAYBILL STATUS WITH LOADING
-- =============================================================================
--
-- loading.pending
--      ↓
-- loading.confirmed
--      ↓
-- waybill.loading_confirmed
--
-- loading.cancelled
--      ↓
-- waybill.cancelled
-- =============================================================================

CREATE OR REPLACE FUNCTION public.sync_waybill_status_from_loading()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN

  IF NEW.status = 'confirmed' THEN

    UPDATE public.waybills
    SET status = 'loading_confirmed'
    WHERE id = NEW.waybill_id
      AND company_id = NEW.company_id
      AND status = 'issued';


  ELSIF NEW.status = 'cancelled' THEN

    UPDATE public.waybills
    SET status = 'cancelled'
    WHERE id = NEW.waybill_id
      AND company_id = NEW.company_id
      AND status = 'issued';

  END IF;


  RETURN NEW;
END;
$$;


CREATE TRIGGER trg_sync_waybill_status_from_loading
  AFTER INSERT OR UPDATE OF status ON public.loading
  FOR EACH ROW
  EXECUTE FUNCTION public.sync_waybill_status_from_loading();


