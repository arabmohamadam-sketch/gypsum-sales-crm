-- =============================================================================
-- 6. WAYBILL ITEMS
-- =============================================================================

CREATE TABLE public.waybill_items (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),

  company_id uuid NOT NULL
    REFERENCES public.companies (id)
    ON DELETE RESTRICT,

  waybill_id uuid NOT NULL
    REFERENCES public.waybills (id)
    ON DELETE RESTRICT,

  order_item_id uuid NOT NULL
    REFERENCES public.order_items (id)
    ON DELETE RESTRICT,

  product_id uuid NOT NULL
    REFERENCES public.products (id)
    ON DELETE RESTRICT,

  -- Snapshot values
  product_name_snapshot text NOT NULL,

  quantity integer NOT NULL,

  weight_kg_snapshot smallint NOT NULL,

  -- Automatic tonnage calculation
  tonnage numeric(14, 4)
    GENERATED ALWAYS AS (
      (
        quantity::numeric
        *
        weight_kg_snapshot::numeric
      ) / 1000.0
    )
    STORED,

  created_at timestamptz NOT NULL
    DEFAULT timezone('utc', now()),

  updated_at timestamptz NOT NULL
    DEFAULT timezone('utc', now()),

  deleted_at timestamptz,

  CONSTRAINT waybill_items_quantity_positive
    CHECK (quantity > 0),

  CONSTRAINT waybill_items_weight_kg_valid
    CHECK (weight_kg_snapshot IN (25, 30))
);


