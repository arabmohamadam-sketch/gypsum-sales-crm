-- =============================================================================
-- Gypsum Sales CRM — Waybills and Loading Confirmation
-- =============================================================================
-- Flow:
--   confirmed order -> order item -> waybill -> waybill number
--   -> loading confirmation
--
-- Design rules:
--   * Waybills belong to an order and are tenant-scoped by company_id.
--   * A waybill item belongs to exactly one order item.
--   * A waybill can only be created for a confirmed order.
--   * One active waybill is allowed per order item.
--   * Product / quantity / weight are snapshotted on the waybill item.
--   * Waybill numbers are generated by PostgreSQL and are unique.
--   * Loading confirmation is kept in a separate 1:1 table.
-- =============================================================================

BEGIN;

-- =============================================================================
-- 1. ENUMS
-- =============================================================================

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_type
    WHERE typnamespace = 'public'::regnamespace
      AND typname = 'waybill_status'
  ) THEN
    CREATE TYPE public.waybill_status AS ENUM (
      'draft',
      'issued',
      'loading_confirmed',
      'cancelled'
    );
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM pg_type
    WHERE typnamespace = 'public'::regnamespace
      AND typname = 'loading_status'
  ) THEN
    CREATE TYPE public.loading_status AS ENUM (
      'pending',
      'confirmed',
      'cancelled'
    );
  END IF;
END $$;


-- =============================================================================
-- 2. WAYBILLS
-- =============================================================================

CREATE TABLE public.waybills (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),

  company_id uuid NOT NULL
    REFERENCES public.companies (id)
    ON DELETE RESTRICT,

  order_id uuid NOT NULL
    REFERENCES public.orders (id)
    ON DELETE RESTRICT,

  -- System generated unique waybill number
  waybill_number bigint
    GENERATED ALWAYS AS IDENTITY
    UNIQUE,

  -- Stored as Gregorian date in database.
  -- UI will display Jalali date.
  waybill_date date NOT NULL
    DEFAULT (timezone('utc', now()))::date,

  status public.waybill_status NOT NULL
    DEFAULT 'draft',

  notes text,

  issued_at timestamptz,

  issued_by uuid
    REFERENCES public.users (id)
    ON DELETE RESTRICT,

  created_at timestamptz NOT NULL
    DEFAULT timezone('utc', now()),

  updated_at timestamptz NOT NULL
    DEFAULT timezone('utc', now()),

  deleted_at timestamptz,

  CONSTRAINT waybills_issued_fields_consistent
  CHECK (
    (
      status = 'draft'
      AND issued_at IS NULL
    )
    OR
    status IN (
      'issued',
      'loading_confirmed',
      'cancelled'
    )
  )
);


